// New dictionaries are packaged scripts, loaded before this service.
Object.assign(I18N_LOCALES, globalThis.TabOutLocales || {});
const LANGUAGE_PREFERENCE_KEY = 'interfaceLanguageV1';
const SUPPORTED_LANGUAGES = Object.freeze(['en', 'zh-CN', 'zh-TW', 'ja']);
const LANGUAGE_OPTIONS = Object.freeze([
  { value: 'auto', key: 'settings.languageAuto' },
  { value: 'en', label: 'English' },
  { value: 'zh-CN', label: '简体中文' },
  { value: 'zh-TW', label: '繁體中文' },
  { value: 'ja', label: '日本語' },
]);

function matchSupportedLocale(value) {
  const parts = String(value || '').replace(/_/g, '-').toLowerCase().split('-');
  if (parts[0] === 'en') return 'en';
  if (parts[0] === 'ja') return 'ja';
  if (parts[0] !== 'zh') return null;
  if (parts.includes('hant')) return 'zh-TW';
  if (parts.includes('hans')) return 'zh-CN';
  return parts.some(part => ['tw', 'hk', 'mo'].includes(part)) ? 'zh-TW' : 'zh-CN';
}
function _detectLocale() {
  const languages = globalThis.navigator?.languages || [];
  for (const language of [...languages, globalThis.navigator?.language]) {
    const matched = matchSupportedLocale(language);
    if (matched) return matched;
  }
  try { return matchSupportedLocale(globalThis.chrome?.i18n?.getUILanguage?.()) || 'en'; }
  catch { return 'en'; }
}
function normalizeLanguagePreference(value) {
  return SUPPORTED_LANGUAGES.includes(value) ? value : 'auto';
}
let _languagePreference = 'auto';
let _currentLocale = _detectLocale();
const languageListeners = new Set();
function applyDocumentLanguage() {
  if (globalThis.document?.documentElement) globalThis.document.documentElement.lang = _currentLocale;
}
const languageReady = (async () => {
  try {
    const stored = await globalThis.chrome?.storage?.local?.get(LANGUAGE_PREFERENCE_KEY);
    _languagePreference = normalizeLanguagePreference(stored?.[LANGUAGE_PREFERENCE_KEY]);
  } catch { /* Language is optional: an unavailable preference must not block the dashboard. */ }
  _currentLocale = _languagePreference === 'auto' ? _detectLocale() : _languagePreference;
  applyDocumentLanguage();
})();
let languageSaveQueue = Promise.resolve();
function setLanguage(value) {
  const preference = normalizeLanguagePreference(value);
  const save = async () => {
    await languageReady;
    // Persist first. A failed write leaves the old preference and UI intact.
    await globalThis.chrome.storage.local.set({ [LANGUAGE_PREFERENCE_KEY]: preference });
    _languagePreference = preference;
    _currentLocale = preference === 'auto' ? _detectLocale() : preference;
    applyDocumentLanguage();
    await Promise.allSettled([...languageListeners].map(listener => Promise.resolve().then(() => listener(_currentLocale))));
    return _currentLocale;
  };
  const result = languageSaveQueue.then(save);
  languageSaveQueue = result.catch(() => {});
  return result;
}

const recentTranslations = new Map();
/** Look up a packaged string and interpolate named placeholders. */
function t(key, params) {
  const dictionary = I18N_LOCALES[_currentLocale] || {};
  const str = Object.hasOwn(dictionary, key) ? dictionary[key] : Object.hasOwn(I18N_LOCALES.en, key) ? I18N_LOCALES.en[key] : key;
  const result = params ? str.replace(/\{(\w+)\}/g, (_, k) => params[k] !== undefined ? params[k] : `{${k}}`) : str;
  recentTranslations.set(result, { key, params: params ? { ...params } : undefined });
  if (recentTranslations.size > 512) recentTranslations.delete(recentTranslations.keys().next().value);
  return result;
}
function tPlural(singularKey, pluralKey, n, extraParams) {
  const key = new Intl.PluralRules(_currentLocale).select(n) === 'one' ? singularKey : pluralKey;
  return t(key, { n, ...extraParams });
}
const TabOutI18n = {
  ready: languageReady,
  options: LANGUAGE_OPTIONS,
  get locale() { return _currentLocale; },
  get preference() { return _languagePreference; },
  setLanguage,
  describeTranslation(text) { return recentTranslations.get(text); },
  translateDescriptor(descriptor) { return descriptor ? t(descriptor.key, descriptor.params) : null; },
  onChange(listener) { languageListeners.add(listener); return () => languageListeners.delete(listener); },
  formatDate(value, options) { return new Intl.DateTimeFormat(_currentLocale, options).format(new Date(value)); },
};
globalThis.TabOutI18n = TabOutI18n;
if (typeof module !== 'undefined') module.exports = { I18N_LOCALES, t, tPlural, matchSupportedLocale, _detectLocale, normalizeLanguagePreference, TabOutI18n };
